// Generated by tools/extract_skate_tower_support.py from the original palace
// and the authored plinth. A dense 100 KiB profile avoids loading/cutting the
// large source mesh while rejecting candidate parcels. +inf means no support.
fn support_profile()-> &'static [u8] { static DATA:std::sync::OnceLock<Vec<u8>>=std::sync::OnceLock::new(); DATA.get_or_init(||std::fs::read(std::env::var_os("JAKMC_SUPPORT_PROFILE").expect("owned support profile input")).expect("read generated support profile")) }
fn support_height(x:i32,z:i32)->Option<f32>{
    if !(FOOTPRINT_MIN[0]..FOOTPRINT_MAX[0]).contains(&x)
        || !(FOOTPRINT_MIN[1]..FOOTPRINT_MAX[1]).contains(&z){return None;}
    let i=((z-FOOTPRINT_MIN[1])*SIZE+x-FOOTPRINT_MIN[0])as usize*4;
    let y=f32::from_le_bytes(support_profile()[i..i+4].try_into().unwrap());
    y.is_finite().then_some(y)
}
/// Lowest integer contact of the visible native base, plinth/piers or porch.
/// The interior porch never fills the room: its support remains below skatea.
pub fn support_floor(x:i32,z:i32)->Option<i32>{support_height(x,z).map(|y|y.floor()as i32)}

