const CONTACT_TOLERANCE:f32=1.0/32.0;
fn triangle_distance_sq(p:Vec3,[a,b,c]:[Vec3;3])->f32{
    // Closest-point regions of a triangle (no allocation or square roots).
    let(ab,ac,ap)=(b-a,c-a,p-a);let(d1,d2)=(ab.dot(ap),ac.dot(ap));
    if d1<=0.0&&d2<=0.0{return ap.length_squared();}
    let bp=p-b;let(d3,d4)=(ab.dot(bp),ac.dot(bp));if d3>=0.0&&d4<=d3{return bp.length_squared();}
    let vc=d1*d4-d3*d2;if vc<=0.0&&d1>=0.0&&d3<=0.0{return(p-(a+ab*(d1/(d1-d3)))).length_squared();}
    let cp=p-c;let(d5,d6)=(ab.dot(cp),ac.dot(cp));if d6>=0.0&&d5<=d6{return cp.length_squared();}
    let vb=d5*d2-d1*d6;if vb<=0.0&&d2>=0.0&&d6<=0.0{return(p-(a+ac*(d2/(d2-d6)))).length_squared();}
    let va=d3*d6-d5*d4;if va<=0.0&&d4-d3>=0.0&&d5-d6>=0.0{return(p-(b+(c-b)*((d4-d3)/((d4-d3)+(d5-d6))))).length_squared();}
    let sum=va+vb+vc;if sum.abs()<1e-18{return(p-a).length_squared().min((p-b).length_squared()).min((p-c).length_squared());}
    (p-(a+ab*(vb/sum)+ac*(vc/sum))).length_squared()
}
fn samples(t:&crate::jak_pieces::PieceTri)->[Vec3;7]{
    let[a,b,c]=t.p.map(Vec3::from_array);[a,b,c,(a+b)*0.5,(a+c)*0.5,(b+c)*0.5,(a+b+c)/3.0]
}
fn reconcile_collision(visual:&Column,original:&Column)->(Column,[usize;3]){
    let mut out=Column::default();let mut census=[0,0,0];
    for(&cell,render)in&visual.pieces{
        if render.tris.is_empty(){continue;}
        if let Some(physical)=original.pieces.get(&cell){
            let faithful=physical.tris.iter().all(|t|samples(t).iter().all(|&p|render.tris.iter().any(|v|
                triangle_distance_sq(p,v.p.map(Vec3::from_array))<=CONTACT_TOLERANCE*CONTACT_TOLERANCE)));
            if faithful{out.pieces.insert(cell,physical.clone());census[0]+=1;}
            else{out.pieces.insert(cell,render.clone());census[1]+=1;}
        }else{
            // A visible wall can fall across a cell edge while the simplified
            // OBJ stays in its neighbour. Keep the wall at its visible place.
            let mut physical=render.clone();physical.invalidate_collision();
            physical.tris.retain(|tri|{
                let p=(Vec3::from_array(tri.p[0])+Vec3::from_array(tri.p[1])+Vec3::from_array(tri.p[2]))/3.0;
                (-1..=1).any(|dx|(-1..=1).any(|dy|(-1..=1).any(|dz|{
                    let delta=Vec3::new(dx as f32,dy as f32,dz as f32);
                    original.pieces.get(&(cell.0+dx,cell.1+dy,cell.2+dz)).is_some_and(|piece|piece.tris.iter().any(|t|
                        triangle_distance_sq(p,t.p.map(|v|Vec3::from_array(v)+delta))<=0.125*0.125))
                })))
            });
            if !physical.tris.is_empty(){out.pieces.insert(cell,physical);census[1]+=1;}
        }
    }
    census[2]=original.pieces.keys().filter(|p|!visual.pieces.contains_key(p)).count();
    (out,census)
}

