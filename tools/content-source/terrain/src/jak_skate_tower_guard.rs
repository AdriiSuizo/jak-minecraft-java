//! Source7 admission at an immutable generation epoch. Existing FULL chunks
//! are never redecorated, so a new tower must not intersect any chunk already
//! stored when this feature first opens the dimension. Geometry lookup is
//! deliberately independent: saved and relocated source7 pieces still work.
use minecraftoss_generator::terrain::TerrainGenerator;
use minecraftoss_world::chunk_map::WorldGen;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashMap};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, OnceLock, Weak};

const MANIFEST: &str = "iw4l-source7-generation-v1.json";
const FORMAT: u32 = 1;
type Bounds = (i32, i32, i32, i32);
type Mask = [u64; 16];

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Epoch {
    format: u32,
    seed: i64,
    dimension: String,
    regions: Vec<Region>,
}
#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Region {
    x: i32,
    z: i32,
    occupied: Mask,
}

/// A save/dimension-specific snapshot, never keyed by the world's seed alone.
/// No saved chunk is rewritten and later chunk saves never extend this epoch.
pub struct TowerGenerationGuard {
    baseline: BTreeMap<(i32, i32), Mask>,
    error: Option<String>,
}
impl TowerGenerationGuard {
    pub(crate) fn open(world: &Path, dimension: &str, seed: i64) -> Arc<Self> {
        // A second stream in this process must read the first completed epoch,
        // never independently snapshot chunks generated by the first stream.
        static OPEN: Mutex<()> = Mutex::new(());
        let _opening = OPEN.lock().expect("source7 epoch opener");
        Arc::new(match Self::load_or_create(world, dimension, seed) {
            Ok(guard) => guard,
            Err(error) => {
                diag::warn!(World, "new skate towers disabled for {}: {}", world.display(), error);
                Self { baseline: BTreeMap::new(), error: Some(error) }
            }
        })
    }

    pub fn is_ready(&self) -> bool { self.error.is_none() }
    pub fn error(&self) -> Option<&str> { self.error.as_deref() }
    pub fn blocked_chunks(&self) -> usize {
        self.baseline.values().flat_map(|m| m.iter()).map(|v| v.count_ones() as usize).sum()
    }

    /// Inclusive chunk bounds covering the entire parcel, access street and
    /// clearing halo. One pre-epoch chunk excludes the whole structure.
    pub fn allows(&self, (min_x, min_z, max_x, max_z): Bounds) -> bool {
        if !self.is_ready() || min_x > max_x || min_z > max_z { return false; }
        let (rx0, rx1) = (min_x.div_euclid(32), max_x.div_euclid(32));
        let (rz0, rz1) = (min_z.div_euclid(32), max_z.div_euclid(32));
        for (&(rx, rz), mask) in self.baseline.range((rx0, i32::MIN)..=(rx1, i32::MAX)) {
            if !(rz0..=rz1).contains(&rz) { continue; }
            let x0 = if rx == rx0 { min_x.rem_euclid(32) as u32 } else { 0 };
            let x1 = if rx == rx1 { max_x.rem_euclid(32) as u32 } else { 31 };
            let z0 = if rz == rz0 { min_z.rem_euclid(32) as usize } else { 0 };
            let z1 = if rz == rz1 { max_z.rem_euclid(32) as usize } else { 31 };
            let columns = (((1u64 << (x1 - x0 + 1)) - 1) << x0) as u32;
            for z in z0..=z1 {
                let row = (mask[z / 2] >> ((z % 2) * 32)) as u32;
                if row & columns != 0 { return false; }
            }
        }
        true
    }

    fn load_or_create(world: &Path, dimension: &str, seed: i64) -> Result<Self, String> {
        let base = dimension_dir(world, dimension)?;
        let path = base.join(MANIFEST);
        match std::fs::read(&path) {
            Ok(bytes) => return Self::decode(&bytes, dimension, seed),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(format!("read {}: {e}", path.display())),
        }
        let regions = snapshot_headers(&base.join("region"))?;
        let epoch = Epoch { format: FORMAT, seed, dimension: dimension.into(), regions };
        let bytes = serde_json::to_vec(&epoch).map_err(|e| e.to_string())?;
        std::fs::create_dir_all(&base).map_err(|e| format!("create {}: {e}", base.display()))?;
        publish_once(&path, &bytes)?;
        // Another process may have published first; its immutable epoch wins.
        let saved = std::fs::read(&path).map_err(|e| format!("read committed epoch: {e}"))?;
        Self::decode(&saved, dimension, seed)
    }

    fn decode(bytes: &[u8], dimension: &str, seed: i64) -> Result<Self, String> {
        let epoch: Epoch = serde_json::from_slice(bytes).map_err(|e| format!("invalid source7 epoch: {e}"))?;
        if epoch.format != FORMAT || epoch.seed != seed || epoch.dimension != dimension {
            return Err("source7 epoch format, seed or dimension does not match this world".into());
        }
        let mut baseline = BTreeMap::new();
        for r in epoch.regions {
            if baseline.insert((r.x, r.z), r.occupied).is_some() {
                return Err("duplicate region in source7 epoch".into());
            }
        }
        Ok(Self { baseline, error: None })
    }
}

fn dimension_dir(world: &Path, dimension: &str) -> Result<PathBuf, String> {
    let (namespace, path) = dimension.split_once(':').unwrap_or(("minecraft", dimension));
    if namespace.is_empty() || path.is_empty()
        || namespace.contains(['/', '\\']) || path.contains('\\')
        || path.split('/').any(|p| p.is_empty() || p == "." || p == "..")
        || namespace == "." || namespace == ".." {
        return Err("invalid dimension path for source7 epoch".into());
    }
    Ok(world.join("dimensions").join(namespace).join(path))
}

/// Only the 4 KiB location table is read, never chunk payloads or entities.
/// Any occupied proto status is conservatively treated as visited too.
fn snapshot_headers(dir: &Path) -> Result<Vec<Region>, String> {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(format!("list {}: {e}", dir.display())),
    };
    let mut regions = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| e.to_string())?;
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) != Some("mca") { continue; }
        let name = path.file_stem().and_then(|s| s.to_str()).ok_or("invalid region name")?;
        let parts: Vec<_> = name.split('.').collect();
        if parts.len() != 3 || parts[0] != "r" { return Err(format!("invalid region name: {name}")); }
        let x = parts[1].parse::<i32>().map_err(|_| format!("invalid region X: {name}"))?;
        let z = parts[2].parse::<i32>().map_err(|_| format!("invalid region Z: {name}"))?;
        let mut file = std::fs::File::open(&path).map_err(|e| format!("open {}: {e}", path.display()))?;
        if file.metadata().map_err(|e| e.to_string())?.len() < 8192 {
            return Err(format!("truncated Anvil header: {}", path.display()));
        }
        let mut header = [0u8; 4096];
        file.read_exact(&mut header).map_err(|e| format!("read {}: {e}", path.display()))?;
        let mut occupied = [0u64; 16];
        for (index, location) in header.chunks_exact(4).enumerate() {
            // Even a malformed nonzero entry cannot be admitted as empty.
            if location != [0, 0, 0, 0] { occupied[index / 64] |= 1 << (index % 64); }
        }
        if occupied.iter().any(|&word| word != 0) { regions.push(Region { x, z, occupied }); }
    }
    regions.sort_unstable_by_key(|r| (r.x, r.z));
    Ok(regions)
}

fn publish_once(path: &Path, bytes: &[u8]) -> Result<(), String> {
    use std::sync::atomic::{AtomicU64, Ordering};
    static NEXT: AtomicU64 = AtomicU64::new(0);
    let temp = path.with_extension(format!("json.{}.{}.tmp", std::process::id(), NEXT.fetch_add(1, Ordering::Relaxed)));
    let mut file = std::fs::OpenOptions::new().write(true).create_new(true).open(&temp)
        .map_err(|e| format!("create source7 epoch staging file: {e}"))?;
    let result = (|| {
        file.write_all(bytes).and_then(|_| file.sync_all()).map_err(|e| format!("write source7 epoch: {e}"))?;
        drop(file);
        // Linking a complete file publishes atomically without replacing a
        // winning epoch. Both names are on the same save filesystem (NTFS).
        match std::fs::hard_link(&temp, path) {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => Ok(()),
            Err(e) => Err(format!("commit source7 epoch: {e}")),
        }
    })();
    // Only our newly created staging path, never a user's region or manifest.
    let _ = std::fs::remove_file(&temp);
    result
}

struct Binding { terrain: Weak<TerrainGenerator>, guard: Arc<TowerGenerationGuard> }
fn bindings() -> &'static Mutex<HashMap<usize, Binding>> {
    static BINDINGS: OnceLock<Mutex<HashMap<usize, Binding>>> = OnceLock::new();
    BINDINGS.get_or_init(Default::default)
}
pub(crate) fn bind(terrain: &Arc<TerrainGenerator>, guard: Arc<TowerGenerationGuard>) {
    let mut all = bindings().lock().expect("source7 guard bindings");
    all.retain(|_, b| b.terrain.strong_count() != 0);
    all.insert(Arc::as_ptr(terrain) as usize, Binding { terrain: Arc::downgrade(terrain), guard });
}
pub fn allows(gen: &WorldGen, bounds: Bounds) -> bool {
    let guard = {
        let all = bindings().lock().expect("source7 guard bindings");
        all.get(&(Arc::as_ptr(&gen.terrain) as usize))
            .filter(|b| b.terrain.ptr_eq(&Arc::downgrade(&gen.terrain)))
            .map(|b| b.guard.clone())
    };
    // A raw/offline generator without a save epoch cannot author a partial
    // tower. Geometry/source and deterministic planning do not use this gate.
    guard.is_some_and(|g| g.allows(bounds))
}

#[cfg(test)]
mod tests {
    use super::*;
    fn region(world: &Path, chunks: &[(i32, i32)]) -> Vec<(PathBuf, Vec<u8>)> {
        let dir = dimension_dir(world, "minecraft:overworld").unwrap().join("region");
        std::fs::create_dir_all(&dir).unwrap();
        let mut files = BTreeMap::<_, Vec<u8>>::new();
        for &(x, z) in chunks {
            let path = dir.join(format!("r.{}.{}.mca", x.div_euclid(32), z.div_euclid(32)));
            let raw = files.entry(path).or_insert_with(|| vec![0u8; 8192]);
            let i = (x.rem_euclid(32) + z.rem_euclid(32) * 32) as usize * 4;
            raw[i..i + 4].copy_from_slice(&[0, 0, 2, 1]);
        }
        files.into_iter().map(|(p, bytes)| { std::fs::write(&p, &bytes).unwrap(); (p, bytes) }).collect()
    }

    #[test]
    fn header_snapshot_blocks_the_whole_parcel_and_road_without_touching_chunks() {
        let temp = crate::test_dir::tempdir().unwrap();
        let originals = region(temp.path(), &[(-33, -1), (40, 11)]);
        let guard = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 12345);
        assert!(guard.is_ready(), "{:?}", guard.error());
        assert_eq!(guard.blocked_chunks(), 2);
        assert!(!guard.allows((-40, -12, -20, 5)));
        assert!(!guard.allows((25, 4, 40, 11)), "old access street excludes the parcel too");
        assert!(guard.allows((-32, -1, 39, 10)), "negative region/index math must be exact");
        assert!(!guard.allows((-33, -1, -33, -1)));
        for (path, expected) in originals { assert_eq!(std::fs::read(path).unwrap(), expected); }
    }

    #[test]
    fn epoch_is_immutable_when_new_chunks_are_saved_and_reentered() {
        let temp = crate::test_dir::tempdir().unwrap();
        region(temp.path(), &[(-33, -1)]);
        let first = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 12345);
        let path = dimension_dir(temp.path(), "minecraft:overworld").unwrap().join(MANIFEST);
        let epoch = std::fs::read(&path).unwrap();
        region(temp.path(), &[(40, 11)]); // first half of a newly accepted tower
        let again = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 12345);
        assert!(first.allows((32, 0, 47, 15)) && again.allows((32, 0, 47, 15)));
        assert!(!again.allows((-40, -12, -20, 5)), "blocked old parcel remains blocked");
        assert_eq!(std::fs::read(path).unwrap(), epoch);
        assert_eq!(again.blocked_chunks(), 1, "new saves are not added to the baseline");
    }

    #[test]
    fn equal_seeds_do_not_share_admission_between_saves_or_dimensions() {
        let a = crate::test_dir::tempdir().unwrap();
        let b = crate::test_dir::tempdir().unwrap();
        region(a.path(), &[(2, 3)]);
        let old = TowerGenerationGuard::open(a.path(), "minecraft:overworld", 7);
        let fresh = TowerGenerationGuard::open(b.path(), "minecraft:overworld", 7);
        let other_dimension = TowerGenerationGuard::open(a.path(), "minecraft:the_nether", 7);
        assert!(!old.allows((0, 0, 8, 8)));
        assert!(fresh.allows((0, 0, 8, 8)) && other_dimension.allows((0, 0, 8, 8)));
    }

    #[test]
    fn corrupt_or_mismatched_epoch_fails_closed_and_is_never_replaced() {
        let temp = crate::test_dir::tempdir().unwrap();
        let good = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 7);
        assert!(good.allows((0, 0, 8, 8)));
        assert!(!TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 8).allows((0, 0, 8, 8)));
        let path = dimension_dir(temp.path(), "minecraft:overworld").unwrap().join(MANIFEST);
        std::fs::write(&path, b"interrupted or edited metadata").unwrap();
        let bad = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 7);
        assert!(!bad.is_ready() && !bad.allows((0, 0, 8, 8)));
        assert_eq!(std::fs::read(path).unwrap(), b"interrupted or edited metadata");
    }

    #[test]
    fn incomplete_region_header_cannot_be_mistaken_for_virgin_land() {
        let temp = crate::test_dir::tempdir().unwrap();
        let files = region(temp.path(), &[(0, 0)]);
        std::fs::write(&files[0].0, [0u8; 16]).unwrap();
        let guard = TowerGenerationGuard::open(temp.path(), "minecraft:overworld", 7);
        assert!(!guard.is_ready() && !guard.allows((0, 0, 8, 8)));
        assert!(!dimension_dir(temp.path(), "minecraft:overworld").unwrap().join(MANIFEST).exists());
    }
}
