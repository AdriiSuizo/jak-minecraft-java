_TEXTURA = re.compile(r'^(sp|hv|v1|sn|sw)_(.+?)(_pane|_layer)?$')
_NUMERO = re.compile(r'(?<![x\d])-?0*(\d+)$')


def _minuscula(texto):
    return texto[:1].lower() + texto[1:]


def _textura(path):
    m = _TEXTURA.match(path)
    if not m:
        return None
    zona, nombre, forma = m.groups()
    clave, numero = zona + '_' + nombre, ''
    if clave not in TEXTURAS:
        n = _NUMERO.search(nombre)
        if not n:
            return None
        clave, numero = zona + '_' + nombre[:n.start()], ' ' + n.group(1)
        if clave not in TEXTURAS:
            return None
    base = TEXTURAS[clave] + ' ' + ZONAS[zona] + numero
    if forma == '_pane':
        return 'Lámina de ' + _minuscula(base)
    if forma == '_layer':
        return 'Capa de ' + _minuscula(base)
    return base


def nombre_es(path, titulo):
    """Nombre es_es del bloque jak:<path>; titulo es el que se escribe en en_us."""
    if path in TITULOS:
        return TITULOS[path]
    return _textura(path) or titulo


